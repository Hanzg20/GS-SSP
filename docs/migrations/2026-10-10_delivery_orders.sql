DROP POLICY IF EXISTS "Org members can view delivery orders" ON delivery_orders;
CREATE POLICY "Org members can view delivery orders" ON delivery_orders FOR SELECT TO authenticated
  USING (is_sys_admin() OR org_id IN (SELECT member_org_ids()));
DROP POLICY IF EXISTS "Order managers can insert delivery orders" ON delivery_orders;
CREATE POLICY "Order managers can insert delivery orders" ON delivery_orders FOR INSERT TO authenticated
  WITH CHECK (has_permission('orders.manage') AND (is_sys_admin() OR org_id IN (SELECT member_org_ids())));
DROP POLICY IF EXISTS "Order managers can update delivery orders" ON delivery_orders;
CREATE POLICY "Order managers can update delivery orders" ON delivery_orders FOR UPDATE TO authenticated
  USING (has_permission('orders.manage') AND (is_sys_admin() OR org_id IN (SELECT member_org_ids())));
DROP POLICY IF EXISTS "Order managers can delete delivery orders" ON delivery_orders;
CREATE POLICY "Order managers can delete delivery orders" ON delivery_orders FOR DELETE TO authenticated
  USING (has_permission('orders.manage') AND (is_sys_admin() OR org_id IN (SELECT member_org_ids())));

-- Devices: their org's orders that are unassigned or assigned to them.
DROP POLICY IF EXISTS "Devices can view their delivery orders" ON delivery_orders;
CREATE POLICY "Devices can view their delivery orders" ON delivery_orders FOR SELECT TO authenticated
  USING (
    org_id IN (SELECT org_id FROM device_auth_map WHERE auth_user_id = auth.uid())
    AND (assigned_device_sn IS NULL
         OR assigned_device_sn IN (SELECT device_sn FROM device_auth_map WHERE auth_user_id = auth.uid()))
  );

-- Items follow their order (the subquery is itself subject to delivery_orders' policies).
DROP POLICY IF EXISTS "Visible orders' items are visible" ON delivery_order_items;
CREATE POLICY "Visible orders' items are visible" ON delivery_order_items FOR SELECT TO authenticated
  USING (order_id IN (SELECT id FROM delivery_orders));
DROP POLICY IF EXISTS "Order managers can write delivery order items" ON delivery_order_items;
CREATE POLICY "Order managers can write delivery order items" ON delivery_order_items FOR ALL TO authenticated
  USING (has_permission('orders.manage') AND order_id IN (SELECT id FROM delivery_orders WHERE is_sys_admin() OR org_id IN (SELECT member_org_ids())))
  WITH CHECK (has_permission('orders.manage') AND order_id IN (SELECT id FROM delivery_orders WHERE is_sys_admin() OR org_id IN (SELECT member_org_ids())));

-- Device marks an order paid. Idempotent for a replay of the same payment.
CREATE OR REPLACE FUNCTION public.mark_delivery_order_paid(p_order_id UUID, p_ecr_ref_num TEXT, p_payment_method TEXT)
RETURNS JSON
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_sn TEXT;
  v_org UUID;
  v_order delivery_orders%ROWTYPE;
BEGIN
  SELECT device_sn, org_id INTO v_sn, v_org FROM device_auth_map WHERE auth_user_id = auth.uid();
  IF v_sn IS NULL THEN
    RETURN json_build_object('success', false, 'message', 'not_a_device');
  END IF;

  SELECT * INTO v_order FROM delivery_orders WHERE id = p_order_id FOR UPDATE;
  IF NOT FOUND OR v_order.org_id IS DISTINCT FROM v_org
     OR (v_order.assigned_device_sn IS NOT NULL AND v_order.assigned_device_sn <> v_sn) THEN
    RETURN json_build_object('success', false, 'message', 'order_not_found');
  END IF;

  IF v_order.status = 'PAID' THEN
    RETURN json_build_object('success', v_order.paid_ecr_ref_num = p_ecr_ref_num,
                             'message', CASE WHEN v_order.paid_ecr_ref_num = p_ecr_ref_num THEN 'already_marked' ELSE 'already_paid' END);
  END IF;
  IF v_order.status <> 'OPEN' THEN
    RETURN json_build_object('success', false, 'message', 'order_' || lower(v_order.status));
  END IF;

  UPDATE delivery_orders
     SET status = 'PAID', paid_at = now(), paid_ecr_ref_num = p_ecr_ref_num,
         paid_by_device_sn = v_sn, payment_method = p_payment_method, updated_at = now()
   WHERE id = p_order_id;
  RETURN json_build_object('success', true, 'message', 'marked');
END;
$$;

REVOKE ALL ON FUNCTION public.mark_delivery_order_paid(UUID, TEXT, TEXT) FROM public;
GRANT EXECUTE ON FUNCTION public.mark_delivery_order_paid(UUID, TEXT, TEXT) TO authenticated;

NOTIFY pgrst, 'reload schema';
