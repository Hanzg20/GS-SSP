-- 2026-10-10: delivery_orders / delivery_order_items -- orders a store takes by
-- phone/WeChat, entered in CMP, collected at the door on an Iris handheld (card,
-- or marked cash). Iris's delivery screen was three hard-coded demo orders.
--
-- assigned_device_sn: NULL = every terminal of the org sees the order; set =
-- only that terminal does. Lines carry the product's tax rate at entry time;
-- Iris recomputes tax from the lines with the same rule as a counter sale
-- (SalesTax: summed per rate, rounded half-up once), subtotal/tax_cents here
-- are CMP's display copy. Devices never UPDATE orders directly: they mark one
-- paid through mark_delivery_order_paid(), which checks the caller's device.

CREATE TABLE IF NOT EXISTS delivery_orders (
  id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  org_id              UUID NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  order_no            BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1001) UNIQUE,
  customer_name       TEXT NOT NULL,
  customer_phone      TEXT,
  address             TEXT NOT NULL,
  note                TEXT,
  assigned_device_sn  TEXT REFERENCES devices(sn) ON DELETE SET NULL,
  status              TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'PAID', 'CANCELLED')),
  subtotal_cents      INTEGER NOT NULL DEFAULT 0,
  tax_cents           INTEGER NOT NULL DEFAULT 0,
  paid_at             TIMESTAMPTZ,
  paid_ecr_ref_num    TEXT REFERENCES transactions(ecr_ref_num) ON DELETE SET NULL,
  paid_by_device_sn   TEXT,
  payment_method      TEXT,
  created_by          UUID DEFAULT auth.uid(),
  created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS delivery_orders_org_status_idx ON delivery_orders (org_id, status);

CREATE TABLE IF NOT EXISTS delivery_order_items (
  id                UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id          UUID NOT NULL REFERENCES delivery_orders(id) ON DELETE CASCADE,
  line_no           INTEGER NOT NULL,
  product_id        UUID REFERENCES products(id) ON DELETE SET NULL,
  name              TEXT NOT NULL,
  barcode           TEXT,
  quantity          INTEGER NOT NULL CHECK (quantity > 0),
  unit_price_cents  INTEGER NOT NULL,
  tax_rate_bps      INTEGER NOT NULL DEFAULT 0,
  CONSTRAINT delivery_order_items_order_line_key UNIQUE (order_id, line_no)
);

ALTER TABLE delivery_orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE delivery_order_items ENABLE ROW LEVEL SECURITY;

